// =============================================================================
// Viewer-request function: send the admin host's root to the portal.
// =============================================================================
// admin.<domain>/ would otherwise serve index.html and the SPA would paint the
// marketing site for a second before any client-side redirect ran. This moves
// the decision to the edge, so the marketing page is never delivered to the
// admin host at all.
//
// Only the bare root is rewritten. Deep links (/admin/companies/x), assets and
// the service worker pass through untouched — rewriting those would break
// refreshes and cache-busting.
//
// 302, not 301: a permanent redirect is cached by browsers indefinitely and
// cannot be recalled if the portal's entry path ever changes. The cost of the
// weaker cache is one request on a page a handful of staff open.
//
// Generated by Terraform from `admin-root-redirect.js` — ADMIN_HOST is
// interpolated at apply time. Do not edit the published function in the console.
function handler(event) {
  var request = event.request;
  var headers = request.headers;
  var host = headers.host && headers.host.value ? headers.host.value.toLowerCase() : '';

  if (host === '${admin_host}' && (request.uri === '/' || request.uri === '/index.html')) {
    return {
      statusCode: 302,
      statusDescription: 'Found',
      headers: {
        location: { value: '/admin' },
        // Never let a shared cache hold this on behalf of another hostname.
        'cache-control': { value: 'no-store' },
      },
    };
  }

  return request;
}
