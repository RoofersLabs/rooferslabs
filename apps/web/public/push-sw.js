/**
 * Web Push handlers, imported into the generated Workbox service worker via
 * vite-plugin-pwa `importScripts`. Payload shape: { title, message, url,
 * priority, image } (see apps/api PushService).
 */

/**
 * Notification branding.
 *
 * These are NOT the home-screen icons, and pointing them there is what produced
 * a blank white notification:
 *
 *   icon   is drawn on the platform's own notification surface, which is
 *          near-white in light mode. `/icons/icon-192.png` is the installed-app
 *          icon — a navy mark on a WHITE field — so its field dissolved into
 *          that surface and left what read as an empty box.
 *          `/icons/notification-192.png` inverts it: a navy tile with the white
 *          mark, which reads as the brand on a light or a dark shade.
 *
 *   badge  is drawn by Android as a monochrome silhouette cut from the ALPHA
 *          channel; the colours are discarded. Every home-screen icon here is
 *          deliberately opaque RGB with no alpha at all (iOS composites a
 *          transparent app icon onto black), so as a badge it masked to a solid
 *          filled square — the plain white box in the status bar.
 *          `/icons/notification-badge-96.png` is an alpha-only white glyph.
 *
 * Both are generated by scripts/generate-icons.mjs from the same two polygons as
 * brand/logo.svg, and both are precached (vite.config.ts `includeAssets`) so a
 * push that arrives offline still renders branded rather than blank.
 *
 * Absolute paths on purpose: the service worker is served from the origin root,
 * and these are resolved by the browser's notification renderer rather than by
 * this script, so a relative URL is not reliably rooted here.
 */
const NOTIFICATION_ICON = '/icons/notification-192.png';
const NOTIFICATION_BADGE = '/icons/notification-badge-96.png';

self.addEventListener('push', (event) => {
  let payload = {};
  try {
    payload = event.data ? event.data.json() : {};
  } catch {
    payload = { message: event.data ? event.data.text() : '' };
  }

  const title = payload.title || 'rooferslabs';
  const options = {
    body: payload.message || '',
    // Branding is applied here rather than read from the payload, so a malformed
    // push — or one sent by an older API build that knows nothing about icons —
    // still renders with the logo instead of the platform placeholder.
    icon: NOTIFICATION_ICON,
    badge: NOTIFICATION_BADGE,
    tag: payload.url || 'rooferslabs',
    data: { url: payload.url || '/notifications' },
    // Emergencies stay on screen until the owner interacts with them.
    requireInteraction: payload.priority === 'CRITICAL',
  };

  // The large hero image in an expanded Android notification. Opt-in per push:
  // supplying one unconditionally would make every routine notification take
  // over the shade, and desktop Chrome ignores it either way.
  if (typeof payload.image === 'string' && payload.image) {
    options.image = payload.image;
  }

  event.waitUntil(self.registration.showNotification(title, options));
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const url = (event.notification.data && event.notification.data.url) || '/notifications';

  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((clients) => {
      for (const client of clients) {
        if ('focus' in client) {
          client.navigate(url);
          return client.focus();
        }
      }
      return self.clients.openWindow(url);
    }),
  );
});
